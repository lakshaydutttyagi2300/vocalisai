def q(value) -> str:
    """Write a Python value as an SQL literal."""
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return repr(round(value, 2)) if isinstance(value, float) else str(value)
    return "'" + str(value).replace("'", "''") + "'"


def inserts(table: str, columns: list[str], rows: list[tuple], batch: int = 50) -> str:
    out = []
    for start in range(0, len(rows), batch):
        chunk = rows[start:start + batch]
        values = ",\n  ".join("(" + ", ".join(q(v) for v in row) + ")" for row in chunk)
        out.append(f"INSERT INTO {table} ({', '.join(columns)}) VALUES\n  {values};")
    return "\n".join(out)


def header(title: str, description: str, tables: str) -> str:
    return (f"-- title: {title}\n-- description: {description}\n--\n-- Tables: {tables}\n"
            "-- This file is read-only sample data for the SQL Lab. The app copies it into a\n"
            "-- practice database, so your experiments never change this file.\n"
            "-- Generated by tools/generate_datasets.py\n\nPRAGMA foreign_keys = ON;\n\n")


def email(first: str, last: str, n: int, domain: str = "example.com") -> str:
    return f"{first.lower()}.{last.lower()}{n}@{domain}"


