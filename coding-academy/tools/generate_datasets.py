def quality() -> str:
    rng = random.Random(606)
    rows = []
    rid = 1
    for i in range(1, 41):
        first, last = rng.choice(FIRST), rng.choice(LAST)
        city, country = rng.choice(CITIES)
        mail = email(first, last, i, "mail.example")
        phone = f"+{rng.randint(1, 99)} {rng.randint(100, 999)} {rng.randint(1000, 9999)}"
        joined = (date(2025, 1, 1) + timedelta(days=rng.randint(0, 500))).isoformat()
        spend = round(rng.uniform(0, 2500), 2)
        problem = rng.random()
        if problem < 0.10:
            mail = None
        elif problem < 0.16:
            mail = mail.replace("@", " at ")
        elif problem < 0.22:
            mail = mail.upper()
        if rng.random() < 0.15:
            city = rng.choice([city.lower(), city.upper(), f" {city} "])
        if rng.random() < 0.08:
            phone = None
        if rng.random() < 0.06:
            spend = -spend
        if rng.random() < 0.05:
            joined = "2099-01-01"
        rows.append((rid, first, last, mail, phone, city, country, joined, spend))
        rid += 1
        if rng.random() < 0.18:  # duplicate entries
            dup_mail = mail.lower() if mail and rng.random() < 0.5 else mail
            rows.append((rid, first, last, dup_mail, phone, city.strip() if city else city, country, joined, spend))
            rid += 1
    sql = header("Data quality", "A deliberately messy customer list (duplicates, missing values, inconsistent "
                 "spelling, impossible values) for data-quality investigations.", "customers_raw")
    sql += """CREATE TABLE customers_raw (
    id          INTEGER PRIMARY KEY,
    first_name  TEXT,
    last_name   TEXT,
    email       TEXT,
    phone       TEXT,
    city        TEXT,
    country     TEXT,
    joined_on   TEXT,
    total_spend REAL
);

"""
    sql += inserts("customers_raw", ["id", "first_name", "last_name", "email", "phone", "city", "country",
                                     "joined_on", "total_spend"], rows) + "\n"
    return sql


